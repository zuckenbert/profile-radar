// Regenerates lib/messages-en.js from _locales/en/messages.json.
// The popup uses that copy as an English fallback when it is opened directly as
// a file (demo mode), where chrome.i18n is not available.
// Run after editing the English strings: node scripts/sync-i18n-fallback.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url);
const messages = JSON.parse(readFileSync(new URL('_locales/en/messages.json', root), 'utf8'));
const out = '// Generated by scripts/sync-i18n-fallback.mjs from _locales/en/messages.json. Do not edit by hand.\n'
  + 'globalThis.PROFILE_RADAR_EN = ' + JSON.stringify(messages, null, 2) + ';\n';
const target = new URL('lib/messages-en.js', root);
writeFileSync(target, out);
console.log('wrote', fileURLToPath(target), '(' + Object.keys(messages).length + ' messages)');
